#!/usr/bin/env python3
"""Appendix D — DCT-IV exact-init parameter disturbance.

Reproduces the exact-init disturbance figures (test PSNR vs disturbance
fraction f; the untrained-vs-trained recovery panels; the train-pool top-k
MSE loss at init vs after training) and Table 6 (disturbed-% x rho trained
PSNR) from the committed sweep in data/exact_disturbance/. Default renders
+ verifies; --retrain reruns the sweep.

Folds tools/analysis/render_disturbance_curve.py (which took a single
--base used for BOTH reading the sweep and writing figures/tables) into
read/write-split render_*() functions: the sweep is now read from
data/exact_disturbance/disturbance_sweep.json and figures/tables are
written to the UNCHANGED results/training/4_exact_disturbance/{figures,
tables} paths that the paper build reads (see the DATA_*/RESULTS_*/*_OUT
constants below for the exact literal mapping).

NOTE on data/exact_disturbance/reference/classical_dct4.json: the original
renderer's module docstring claims to read "reference/classical_dct4.json",
but its actual code never opens that file -- every one of its four
render_*() functions reads only disturbance_sweep.json (verified by
inspection; the string "classical_dct4" appears exactly once in
tools/analysis/render_disturbance_curve.py, in the docstring, nowhere in a
function body). This script reads it too, but only for verify()'s
informational headline (the canonical-untrained-DCT-IV reference point),
mirroring how 04_robustness_qft.py's verify() prints classical_div2k.json's
block-FFT reference line -- it is NOT plotted or tabulated here either,
matching the renderer's actual (not documented) behaviour.

--retrain reruns experiments/_train/dct4_disturbance_sweep.py's sweep+
aggregate directly (in-process, via its own main()), redirected via --out
to write into data/exact_disturbance/ instead of its results/ default.
Both generators the task named are present on main and (given real
hardware) would genuinely regenerate the full committed input -- unlike
04_robustness_qft.py's retrain(), nothing here is permanently un-regenerable.
This calls the driver's main() directly rather than shelling out through a
parallel multi-GPU dispatcher; the dispatcher only added parallelism across
idle GPUs over the same (fraction, seed) grid, run here sequentially
instead. Needs a GPU +
pdft.DCT4Basis (parametrization="controlled") + the DIV2K dataset
submodule; the driver itself aborts if --gpu is requested but JAX sees only
CPU, so this does not meaningfully complete in this sandbox.
"""
from __future__ import annotations

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # for _paper_style
from _paper_style import apply_paper_style, PAPER_TEXTWIDTH  # noqa: E402

import difflib
import importlib.util
import json
import subprocess
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

REPO_ROOT = Path(__file__).resolve().parents[1]

# ---------------------------------------------------------------------------
# Path map. INPUT read from data/; OUTPUTS written to the unchanged results/
# paths (the paper build reads these exact results/ locations -- do not move).
# ---------------------------------------------------------------------------
DATA_DISTURBANCE = REPO_ROOT / "data/exact_disturbance"
DATA_SWEEP = DATA_DISTURBANCE / "disturbance_sweep.json"
DATA_CLASSICAL_REF = DATA_DISTURBANCE / "reference/classical_dct4.json"

RESULTS_DISTURBANCE = REPO_ROOT / "results/training/4_exact_disturbance"
FIG_PSNR_VS_F = RESULTS_DISTURBANCE / "figures/disturbance_psnr_vs_f"
FIG_RECOVERY = RESULTS_DISTURBANCE / "figures/disturbance_recovery"
FIG_INIT_LOSS = RESULTS_DISTURBANCE / "figures/disturbance_init_loss"
TABLE_OUT = RESULTS_DISTURBANCE / "tables/disturbance_psnr.tex"

PROVENANCE = "% Auto-generated by experiments/05_robustness_dct_iv.py — do not edit."

# Wong colourblind-safe palette, one (colour, linestyle, marker) per rho.
STYLE = {
    "0.01": ("#0072B2", "-", "o"),    # blue,   solid
    "0.05": ("#E69F00", "--", "s"),   # orange, dashed
    "0.1": ("#009E73", "-.", "^"),    # green,  dashdot
    "0.2": ("#CC79A7", ":", "D"),     # pink,   dotted
}
RHO_KEYS = ["0.01", "0.05", "0.1", "0.2"]
RHO_LABEL = {"0.01": r"$\rho=.01$", "0.05": r"$\rho=.05$",
             "0.1": r"$\rho=.10$", "0.2": r"$\rho=.20$"}


def _pct(fk: str) -> float:
    return float(fk) * 100.0


def _save(fig, out_stem: Path) -> None:
    """Write <out_stem>.pdf and <out_stem>.svg -- both committed formats for
    every disturbance figure (unlike 04's paper figures, which are PDF-only)."""
    out_stem.parent.mkdir(parents=True, exist_ok=True)
    for ext in ("pdf", "svg"):
        fig.savefig(out_stem.with_suffix(f".{ext}"), bbox_inches="tight")
    plt.close(fig)
    print(f"[render] wrote {out_stem}.{{pdf,svg}}")


# ===========================================================================
# Fig — PSNR vs disturbance fraction f (log-x), one colour+style per rho,
# mean+/-sigma band, with the undisturbed exact-init-trained PSNR as a
# per-rho reference line. Ports render_disturbance_curve.py::render_main().
# ===========================================================================
def render_fig_psnr_vs_f(ss: dict, out_stem: Path = FIG_PSNR_VS_F) -> Path:
    fractions = [f"{f:g}" for f in ss["fractions"]]
    xs = np.array([_pct(fk) for fk in fractions])
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    for rk in RHO_KEYS:
        colour, ls, mk = STYLE[rk]
        means = np.array([ss["agg_trained"][fk][rk]["mean"] for fk in fractions])
        stds = np.array([ss["agg_trained"][fk][rk]["std"] for fk in fractions])
        ax.plot(xs, means, ls, color=colour, marker=mk, ms=4, lw=1.6, label=RHO_LABEL[rk])
        ax.fill_between(xs, means - stds, means + stds, color=colour, alpha=0.18, lw=0)
        if ss.get("baseline"):
            base_psnr = ss["baseline"]["psnr_trained"][rk]
            ax.axhline(base_psnr, color=colour, ls=ls, lw=0.8, alpha=0.5)
    ax.set_xscale("log")
    ax.set_xlabel("disturbed parameters (% of 2200 gate entries)")
    ax.set_ylabel("test PSNR (dB)")
    ax.set_xticks(xs)
    ax.set_xticklabels([f"{v:g}" for v in xs])
    ax.grid(True, which="both", ls=":", lw=0.4, alpha=0.5)
    ax.legend(frameon=False, fontsize=8, ncol=2)
    _save(fig, out_stem)
    return out_stem


# ===========================================================================
# Fig — untrained (perturbed init) vs trained PSNR, 2x2 panels (one per rho).
# Ports render_disturbance_curve.py::render_recovery().
# ===========================================================================
def render_fig_recovery(ss: dict, out_stem: Path = FIG_RECOVERY) -> Path:
    fractions = [f"{f:g}" for f in ss["fractions"]]
    xs = np.array([_pct(fk) for fk in fractions])
    fig, axes = plt.subplots(2, 2, figsize=(PAPER_TEXTWIDTH, 5.0), sharex=True)
    for ax, rk in zip(axes.ravel(), RHO_KEYS):
        colour, ls, mk = STYLE[rk]
        tr = np.array([ss["agg_trained"][fk][rk]["mean"] for fk in fractions])
        un = np.array([ss["agg_untrained"][fk][rk]["mean"] for fk in fractions])
        ax.plot(xs, tr, "-", color=colour, marker=mk, ms=4, lw=1.6, label="trained")
        ax.plot(xs, un, ":", color=colour, marker=mk, ms=3, lw=1.3, alpha=0.7,
                label="perturbed init")
        ax.set_xscale("log")
        ax.set_title(RHO_LABEL[rk], fontsize=9)
        ax.grid(True, which="both", ls=":", lw=0.4, alpha=0.5)
        ax.legend(frameon=False, fontsize=7)
    for ax in axes[-1]:
        ax.set_xlabel("disturbed %")
        ax.set_xticks(xs)
        ax.set_xticklabels([f"{v:g}" for v in xs], fontsize=7)
    for ax in axes[:, 0]:
        ax.set_ylabel("PSNR (dB)")
    _save(fig, out_stem)
    return out_stem


# ===========================================================================
# Fig — train-pool top-k MSE loss at perturbed init (rising) vs after
# training (flat) vs disturbance rate. Ports render_init_loss().
# ===========================================================================
def render_fig_init_loss(ss: dict, out_stem: Path = FIG_INIT_LOSS) -> Path:
    fractions = [f"{f:g}" for f in ss["fractions"]]
    xs = np.array([_pct(fk) for fk in fractions])
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    im = np.array([ss["agg_init_loss"][fk]["mean"] for fk in fractions])
    isd = np.array([ss["agg_init_loss"][fk]["std"] for fk in fractions])
    fm = np.array([ss["agg_final_loss"][fk]["mean"] for fk in fractions])
    fsd = np.array([ss["agg_final_loss"][fk]["std"] for fk in fractions])
    ax.plot(xs, im, "-", color="#D55E00", marker="o", ms=4, lw=1.6,
            label="at init (perturbed)")
    ax.fill_between(xs, im - isd, im + isd, color="#D55E00", alpha=0.18, lw=0)
    ax.plot(xs, fm, "--", color="#009E73", marker="s", ms=4, lw=1.6,
            label="after training")
    ax.fill_between(xs, fm - fsd, fm + fsd, color="#009E73", alpha=0.18, lw=0)
    if ss.get("baseline") and ss["baseline"].get("init_loss") is not None:
        ax.axhline(ss["baseline"]["init_loss"], color="k", ls=":", lw=0.9, alpha=0.55,
                   label="exact init")
    ax.set_xscale("log")
    ax.set_xlabel("disturbed parameters (% of 2200 gate entries)")
    ax.set_ylabel("top-$k$ truncation loss $\\mathcal{L}_k$ (train pool)")
    ax.set_xticks(xs)
    ax.set_xticklabels([f"{v:g}" for v in xs])
    ax.grid(True, which="both", ls=":", lw=0.4, alpha=0.5)
    ax.legend(frameon=False, fontsize=8)
    _save(fig, out_stem)
    return out_stem


# ===========================================================================
# Table 6 — disturbed-% x rho trained PSNR mean+/-sigma, with the f=0 exact
# baseline row. Ports render_disturbance_curve.py::render_table().
# ===========================================================================
def render_table_disturbance(ss: dict, out_path: Path = TABLE_OUT) -> Path:
    """NOTE on the provenance line: the original render_table() emitted no
    provenance comment at all (results/.../disturbance_psnr.tex at HEAD has
    none -- unlike seed_variance.tex, which already carried one before
    04_robustness_qft.py). This script adds one line naming itself, matching
    the 04_robustness_qft.py convention. Only that comment line is expected
    to change across regenerations -- verify() strips it before comparing,
    exactly like 04's _strip_provenance()."""
    fractions = [f"{f:g}" for f in ss["fractions"]]
    lines = [PROVENANCE,
             r"\begin{tabular}{lrrrr}", r"\toprule",
             r"disturbed \% & $\rho{=}.01$ & $\rho{=}.05$ & $\rho{=}.10$ & $\rho{=}.20$ \\",
             r"\midrule"]
    if ss.get("baseline"):
        b = ss["baseline"]["psnr_trained"]
        lines.append("0 (exact) & " + " & ".join(f"{b[rk]:.2f}" for rk in RHO_KEYS) + r" \\")
        lines.append(r"\midrule")
    for fk in fractions:
        cells = []
        for rk in RHO_KEYS:
            a = ss["agg_trained"][fk][rk]
            cells.append(f"{a['mean']:.2f}\\,$\\pm$\\,{a['std']:.2f}")
        lines.append(f"{_pct(fk):g} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    text = "\n".join(lines) + "\n"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text)
    print(f"[table] wrote {out_path}")
    return out_path


# ===========================================================================
# render() / verify()
# ===========================================================================
def _load_sweep(path: Path = DATA_SWEEP) -> dict:
    if not path.exists():
        raise RuntimeError(f"[render] no {path} -- run with --retrain first "
                            f"or restore the committed data/ input.")
    return json.loads(path.read_text())


def render() -> dict:
    """Run all three figure renders + Table 6 into their results/ output
    paths, reading the sweep from data/exact_disturbance/."""
    apply_paper_style()
    # original renderer's own local override (kept verbatim; only font.size
    # and axes.titlesize deviate from apply_paper_style()'s defaults).
    plt.rcParams.update({"font.size": 9, "axes.titlesize": 9})
    ss = _load_sweep()
    outputs = {}
    outputs["fig_psnr_vs_f"] = render_fig_psnr_vs_f(ss)
    outputs["fig_recovery"] = render_fig_recovery(ss)
    outputs["fig_init_loss"] = render_fig_init_loss(ss)
    outputs["table"] = render_table_disturbance(ss)
    return outputs


def _git_show(rel_path: str) -> str | None:
    """Committed HEAD content of a repo-relative path, or None if untracked."""
    res = subprocess.run(["git", "show", f"HEAD:{rel_path}"], cwd=REPO_ROOT,
                          capture_output=True, text=True)
    return res.stdout if res.returncode == 0 else None


def _strip_provenance(text: str) -> str:
    """Drop the "% Auto-generated by ..." comment line -- see
    render_table_disturbance()'s docstring for why this line is allowed to
    differ from an older committed copy while every data row must not."""
    return "\n".join(ln for ln in text.splitlines()
                      if not ln.startswith("% Auto-generated by"))


def verify() -> bool:
    """Assert results/.../tables/disturbance_psnr.tex has the same DATA ROWS
    as the committed one (header + every numeric row + rules); the added
    provenance comment line is exempt from this check by design. Prints the
    PSNR-vs-f headline straight from the sweep JSON, independent of table
    formatting. Returns True/False."""
    if not TABLE_OUT.exists():
        print(f"[verify] FAIL: {TABLE_OUT} does not exist (run render() first)",
              file=sys.stderr)
        return False

    current = TABLE_OUT.read_text()
    rel = TABLE_OUT.relative_to(REPO_ROOT).as_posix()
    committed = _git_show(rel)
    if committed is None:
        print(f"[verify] WARN: {rel} is not tracked at HEAD; skipping data-row check")
        ok = True
    else:
        ok = _strip_provenance(current) == _strip_provenance(committed)
        print("[verify] TABLE DATA IDENTICAL (provenance comment may differ by design)"
              if ok else "[verify] TABLE DATA CHANGED — investigate")
        if not ok:
            print(f"[verify] diff against HEAD:{rel} (provenance line excluded):",
                  file=sys.stderr)
            for line in difflib.unified_diff(
                    _strip_provenance(committed).splitlines(),
                    _strip_provenance(current).splitlines(),
                    "committed", "regenerated", lineterm=""):
                print(line, file=sys.stderr)

    ss = _load_sweep()
    fractions = [f"{f:g}" for f in ss["fractions"]]
    base = ss.get("baseline")
    print("[verify] PSNR-vs-f headline (rho=.20, trained, dB):")
    if base:
        print(f"[verify]   f=0% (exact init): {base['psnr_trained']['0.2']:.2f}")
    for fk in fractions:
        a = ss["agg_trained"][fk]["0.2"]
        print(f"[verify]   f={_pct(fk):g}%: {a['mean']:.2f} +/- {a['std']:.2f} dB (n={a['n']})")

    if DATA_CLASSICAL_REF.exists():
        classical = json.loads(DATA_CLASSICAL_REF.read_text())
        cd = classical.get("canonical_dct4", {}).get("psnr", {}).get("0.2")
        if cd is not None:
            print(f"[verify]   classical DCT-IV (untrained) reference @ rho=.20 = {cd:.2f} dB")

    return ok


# ===========================================================================
# retrain() — rerun the exact-init disturbance sweep (GPU + pdft.DCT4Basis +
# DIV2K submodule required; does not meaningfully complete in-sandbox). See
# the module docstring above for exactly what this does.
# ===========================================================================
def _run_module_main(script_path: Path, argv: list[str]) -> int:
    """Load `script_path` as a module (without executing its __main__ guard)
    and call its main() with a patched sys.argv, equivalent to
    `python script_path <argv...>` but in-process. Mirrors
    04_robustness_qft.py's helper of the same name."""
    spec = importlib.util.spec_from_file_location(script_path.stem, script_path)
    mod = importlib.util.module_from_spec(spec)
    old_argv = sys.argv
    try:
        sys.argv = [str(script_path)] + argv
        spec.loader.exec_module(mod)
        return mod.main()
    finally:
        sys.argv = old_argv


_ALL_FRACTIONS = (0.0, 0.001, 0.002, 0.005, 0.01, 0.02, 0.05, 0.10, 0.20, 0.50, 1.00)


def retrain(gpu: int | None = None, seeds: str = "1-3", epochs: int = 1008,
            topk_ratio: float = 0.10, sigma: float = 0.1) -> int:
    """Rerun experiments/_train/dct4_disturbance_sweep.py's sweep+aggregate,
    regenerating data/exact_disturbance/disturbance_sweep.json (+ per-cell
    _runs/*.json under data/exact_disturbance/_runs/). Defaults (seeds 1-3,
    epochs 1008, topk_ratio 0.10, sigma 0.1) match the committed sweep's
    metadata exactly.

    fractions are passed explicitly with 0.0 included: the driver's own
    --fractions default omits the f=0 baseline (it was normally added by the
    now-removed multi-GPU dispatcher's --with-baseline flag, which this
    function does not go through). Omitting it here would silently drop the
    baseline row/reference line that Table 6 and both PSNR figures read
    from ss["baseline"].

    Needs a GPU + pdft.DCT4Basis (parametrization="controlled") + the DIV2K
    dataset submodule; the driver aborts by itself if --gpu is requested but
    JAX only sees CPU.
    """
    print(f"[retrain] === dct4_disturbance_sweep: exact-init disturbance sweep "
          f"(seeds={seeds}, epochs={epochs}, topk_ratio={topk_ratio}, sigma={sigma}) ===")
    fractions = [f"{f:g}" for f in _ALL_FRACTIONS]
    argv = ["--seeds", seeds, "--fractions", *fractions,
            "--epochs", str(epochs), "--topk-ratio", str(topk_ratio),
            "--sigma", str(sigma), "--out", str(DATA_DISTURBANCE)]
    if gpu is not None:
        argv = ["--gpu", str(gpu)] + argv
    rc = _run_module_main(
        REPO_ROOT / "experiments/_train/dct4_disturbance_sweep.py", argv)
    if rc != 0:
        print(f"[retrain] dct4_disturbance_sweep exited {rc}", file=sys.stderr)
        return rc
    print(f"[retrain] done. Wrote {DATA_DISTURBANCE / 'disturbance_sweep.json'}")
    return 0


# ===========================================================================
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--retrain", action="store_true", default=False,
                    help="Rerun the exact-init disturbance sweep to "
                         "regenerate data/exact_disturbance/ (needs GPU + "
                         "pdft.DCT4Basis + DIV2K submodule). Default: "
                         "render + verify only.")
    ap.add_argument("--gpu", type=int, default=None,
                    help="GPU index, forwarded to --retrain.")
    ap.add_argument("--seeds", default="1-3", help="--retrain seed spec.")
    ap.add_argument("--epochs", type=int, default=1008,
                    help="--retrain step budget.")
    ap.add_argument("--topk-ratio", type=float, default=0.10,
                    help="--retrain training top-k ratio.")
    ap.add_argument("--sigma", type=float, default=0.1,
                    help="--retrain on-manifold perturbation sigma.")
    args = ap.parse_args(argv)

    if args.retrain:
        return retrain(gpu=args.gpu, seeds=args.seeds, epochs=args.epochs,
                       topk_ratio=args.topk_ratio, sigma=args.sigma)

    render()
    ok = verify()
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
