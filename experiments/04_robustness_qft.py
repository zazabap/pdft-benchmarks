# Fig 10 — unfreeze training-dynamics grid.
# Ports tools/analysis/render_qft_unfreeze.py::_render_combined(paper_style=True).
# ===========================================================================
_STYLE = {
    "bg": ("#0072B2", "-", "block-growth"),
    "lr": ("#E69F00", "--", "left→right"),
    "rl": ("#009E73", "-.", "right→left"),
}
_COMBINED_DATASETS = [
    ("quickdraw_5q", "QuickDraw  (m=n=5)"),
    ("div2k_8q", "DIV2K  (m=n=8)"),
    ("tuberlin_8q", "TU-Berlin  (m=n=8)"),
]
_COMBINED_INITS = [("identity", "identity init"), ("random", "random init")]


def _final_psnr(trace: dict, ratio: str = "0.2"):
    """Final-stage test PSNR at `ratio` from a trace dict, or None if absent."""
    for st in reversed(trace.get("stages", [])):
        p = (st.get("extra") or {}).get("psnr") or {}
        if ratio in p:
            return p[ratio]
    return None


def _gate_labels(m: int, n: int):
    """storage-index -> human gate name (H{q} / CP{c,t}) for QFTBasis(m, n)."""
    gl = []
    for off, mm in [(0, m), (m, n)]:
        for i in range(1, mm + 1):
            gl.append(("H", (i + off,)))
            for j in range(i + 1, mm + 1):
                gl.append(("CP", (j + off, i + off)))
    order = sorted(range(len(gl)), key=lambda k: gl[k][0] != "H")
    out = [None] * len(gl)
    for pos, e in enumerate(order):
        kind, q = gl[e]
        out[pos] = f"H{q[0]}" if kind == "H" else f"CP{q[0]},{q[1]}"
    return out


def _top_gate_marks(trace: dict, k: int = 4):
    """The k stages with the largest MSE drop: (start_step, pre-drop loss, gate
    label) — i.e. which gate, thawed at which step, caused each big improvement."""
    stages = trace.get("stages", [])
    steps = trace.get("steps", [])
    m, n = trace.get("m"), trace.get("n")
    labels = _gate_labels(m, n) if m and n else None
    l0 = steps[0]["loss"] if steps else None
    marks = []
    for idx, st in enumerate(stages):
        pre = stages[idx - 1]["final_loss"] if idx > 0 else (
            l0 if l0 is not None else st.get("final_loss"))
        drop = pre - st.get("final_loss", pre)
        gi = st.get("gate_index")
        lab = labels[gi] if labels and gi is not None and gi < len(labels) else str(gi)
        marks.append((drop, st["start_step"], pre, lab))
    marks.sort(reverse=True)
    return marks[:k]


def render_fig10_unfreeze(read_base: Path = DATA_UNFREEZE,
                           write_base: Path = RESULTS_UNFREEZE) -> Path:
    """Training-dynamics grid: rows = init (identity, random), cols = dataset,
    one absolute-MSE curve per unfreeze ordering. Reads
    <read_base>/<dataset>/<init>/<ordering>/trace.json; writes
    <write_base>/figures/paper/training_dynamics.pdf."""
    cols = [(tag, lab) for tag, lab in _COMBINED_DATASETS
            if any((read_base / tag / init).exists() for init, _ in _COMBINED_INITS)]
    rows = [(init, lab) for init, lab in _COMBINED_INITS
            if any((read_base / tag / init).exists() for tag, _ in _COMBINED_DATASETS)]
    if not cols or not rows:
        raise RuntimeError(f"[fig10] no <dataset>/<init> subdirs under {read_base}")

    figw = PAPER_TEXTWIDTH
    figh = 2.3 * len(rows)
    fig, axes = plt.subplots(len(rows), len(cols), figsize=(figw, figh),
                              squeeze=False, sharex="col")
    any_curve = False
    for r, (init, init_lab) in enumerate(rows):
        for c, (tag, ds_lab) in enumerate(cols):
            ax = axes[r][c]
            finals = []  # (color, leg, mse_end, psnr) for the corner annotation
            for name, (color, ls, leg) in _STYLE.items():
                tj = read_base / tag / init / name / "trace.json"
                if not tj.exists():
                    continue
                trace = json.loads(tj.read_text())
                steps = trace["steps"]
                if not steps:
                    continue
                xs = [s["step"] for s in steps]
                loss = [s["loss"] for s in steps]  # absolute top-k MSE (not L/L0)
                ax.plot(xs, loss, color=color, ls=ls, lw=1.3, label=leg)
                ax.plot([xs[-1]], [loss[-1]], marker="o", ms=3.5, color=color)
                for _drop, xstep, yloss, glab in _top_gate_marks(trace, k=4):
                    ax.annotate(glab, xy=(xstep, yloss), xytext=(2, 1),
                                textcoords="offset points", rotation=90,
                                fontsize=5, color=color, va="bottom", ha="left",
                                annotation_clip=True)
                    ax.plot([xstep], [yloss], marker="|", ms=5, color=color, mew=0.8)
                finals.append((color, leg, loss[-1], _final_psnr(trace)))
                any_curve = True
            for i, (color, leg, mse, psnr) in enumerate(finals):
                txt = f"test {psnr:.1f} dB" if psnr is not None else f"MSE {mse:.4g}"
                ax.text(0.97, 0.96 - 0.085 * i, txt, transform=ax.transAxes,
                        ha="right", va="top", fontsize=6.5, color=color)
            ax.grid(True, alpha=0.25, lw=0.5)
            ax.tick_params(labelsize=7)
            if r == len(rows) - 1:
                ax.set_xlabel("cumulative training step", fontsize=8)
            if c == 0:
                ax.set_ylabel(f"{init_lab}\ntraining top-$k$ MSE loss", fontsize=8.5)
            if r == 0 and c == 0:
                ax.legend(frameon=False, fontsize=7.5)

    if not any_curve:
        raise RuntimeError(f"[fig10] no trace.json found under {read_base}/<dataset>/<init>/")

    fig.tight_layout()
    out = write_base / "figures" / "paper" / "training_dynamics.pdf"
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print(f"[render] wrote {out}")
    return out


# ===========================================================================
# Fig 11a — seed init distribution (L0 histogram + PCA scatter).
# Ports tools/analysis/render_init_distribution.py main(--from-json --paper-style).
# ===========================================================================
def _load_init_distribution_json(path: Path):
    d = json.loads(path.read_text())
    seeds = [int(s) for s in d["seeds"]]
    L0 = np.array([d["L0"][str(s)] for s in seeds])
    scores = np.array([d["pca"]["coords"][str(s)] for s in seeds])
    var_ratio = np.array(d["pca"]["explained_var_ratio"])
    return seeds, L0, scores, var_ratio


def _draw_init_L0(ax, L0, n_seeds):
    ax.hist(L0, bins=24, color="#0072B2", alpha=0.75)
    ax.axvline(L0.mean(), color="k", ls="--", lw=1.2,
               label=f"mean {L0.mean():.1f} ($\\sigma$={L0.std(ddof=1):.1f})")
    ax.set_xlabel("initial top-$k$ MSE loss $L_0$  (random init)", fontsize=8.5)
    ax.set_ylabel(f"# seeds ({n_seeds} total)", fontsize=8.5)
    ax.legend(frameon=False, fontsize=7.5)


def _draw_init_pca(fig, ax, scores, L0, var_ratio):
    sc = ax.scatter(scores[:, 0], scores[:, 1], c=L0, cmap="viridis",
                     s=22, edgecolors="none")
    cb = fig.colorbar(sc, ax=ax, fraction=0.046, pad=0.04)
    cb.set_label("$L_0$", fontsize=8)
    ax.set_xlabel(f"PC1 ({var_ratio[0]*100:.0f}% var)", fontsize=8.5)
    ax.set_ylabel(f"PC2 ({var_ratio[1]*100:.0f}% var)", fontsize=8.5)


def render_fig11a_init_distribution(read_base: Path = DATA_SEED_DIV2K,
                                     write_base: Path = RESULTS_SEED_DIV2K) -> Path:
    """L0 histogram + PCA scatter of the per-seed Haar inits. Reads
    <read_base>/reference/init_distribution.json; writes
    <write_base>/figures/paper/init_distribution.pdf."""
    src = read_base / "reference" / "init_distribution.json"
    if not src.exists():
        raise RuntimeError(f"[fig11a] no {src}")
    seeds, L0, scores, var_ratio = _load_init_distribution_json(src)

    fig, (axA, axB) = plt.subplots(1, 2, figsize=(PAPER_TEXTWIDTH, 2.6),
                                    gridspec_kw={"width_ratios": [1.0, 1.15]})
    _draw_init_L0(axA, L0, len(seeds))
    _draw_init_pca(fig, axB, scores, L0, var_ratio)
    fig.tight_layout()
    out = write_base / "figures" / "paper" / "init_distribution.pdf"
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print(f"[render] wrote {out}")
    print(f"[init-dist] L0 spread: mean={L0.mean():.2f} std={L0.std(ddof=1):.2f} "
          f"min={L0.min():.2f} max={L0.max():.2f}")
    return out


# ===========================================================================
# Fig 11b — per-seed PSNR scatter across keep ratios.
# Ports tools/analysis/render_seed_scatter_ratios.py main(--paper-style).
# ===========================================================================
_SCATTER_STYLE = {
    "bg": ("#0072B2", "block-growth"),
    "lr": ("#E69F00", "left→right"),
    "rl": ("#009E73", "right→left"),
}


def render_fig11b_seed_scatter(read_base: Path = DATA_SEED_DIV2K,
                                write_base: Path = RESULTS_SEED_DIV2K,
                                ratios=("0.01", "0.05", "0.1", "0.2")) -> Path:
    """Per-seed PSNR scatter, one panel per keep ratio. Reads
    <read_base>/reference/seed_scatter_ratios.json; writes
    <write_base>/figures/paper/seed_scatter_ratios.pdf."""
    merged_path = read_base / "reference" / "seed_scatter_ratios.json"
    if not merged_path.exists():
        raise RuntimeError(f"[fig11b] no {merged_path}")
    merged = json.loads(merged_path.read_text())
    per_ordering = merged["per_ordering"]
    orderings = [o for o in ("bg", "lr", "rl") if o in per_ordering]
    classical = merged.get("classical")

    fig, axes = plt.subplots(1, len(ratios), figsize=(PAPER_TEXTWIDTH, 2.4), squeeze=False)
    axes = axes[0]
    rng = np.random.default_rng(0)
    for ax, r in zip(axes, ratios):
        for i, o in enumerate(orderings):
            color, _lab = _SCATTER_STYLE[o]
            vals = np.array([v[r] for v in per_ordering[o].values() if r in v])
            if vals.size == 0:
                continue
            jitter = (rng.random(vals.size) - 0.5) * 0.5
            ax.scatter(np.full(vals.size, i) + jitter, vals, s=9, color=color,
                       alpha=0.55, edgecolors="none")
            m = float(vals.mean())
            sd = float(vals.std(ddof=1) if vals.size > 1 else 0.0)
            ax.errorbar(i, m, yerr=sd, fmt="_", color="black", ms=18, lw=1.6,
                        capsize=4, zorder=5)
        if classical:
            if "block_dct_8" in classical and r in classical["block_dct_8"]:
                ax.axhline(classical["block_dct_8"][r], color="0.45", ls=":", lw=1.3,
                           label="block-DCT 8×8")
            if "block_fft_8" in classical and r in classical["block_fft_8"]:
                ax.axhline(classical["block_fft_8"][r], color="k", ls="--", lw=1.2,
                           label="block-FFT 8×8")
        ax.set_xticks(range(len(orderings)))
        ax.set_xticklabels([_SCATTER_STYLE[o][1] for o in orderings], fontsize=7,
                           rotation=20, ha="right")
        ax.set_title(f"$\\rho = {r}$", fontsize=9)
    axes[0].set_ylabel("test PSNR (dB)", fontsize=8.5)
    if classical:
        axes[-1].legend(frameon=False, fontsize=7, loc="lower left")

    fig.tight_layout()
    out = write_base / "figures" / "paper" / "seed_scatter_ratios.pdf"
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)
    print(f"[render] wrote {out}")
    return out


