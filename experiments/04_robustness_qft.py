def render() -> dict:
    """Run all four sub-renders into their results/ output paths. Each figure
    renderer applies the shared paper style itself."""
    outputs = {}
    outputs["fig10"] = render_fig10_unfreeze()
    outputs["fig11a"] = render_fig11a_init_distribution()
