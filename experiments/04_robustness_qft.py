def _git_show(rel_path: str) -> str | None:
    """Committed HEAD content of a repo-relative path, or None if untracked."""
    res = subprocess.run(["git", "show", f"HEAD:{rel_path}"], cwd=REPO_ROOT,
                          capture_output=True, text=True)
    return res.stdout if res.returncode == 0 else None


def _strip_provenance(text: str) -> str:
    """Drop the "% Auto-generated by ..." comment line. That line intentionally
    names whichever script last wrote the file, so it is allowed to differ
    from an older committed copy; everything else (caption, header, every
    data row, rules) must not."""
    return "\n".join(ln for ln in text.splitlines()
                      if not ln.startswith("% Auto-generated by"))


def verify() -> bool:
    """Assert results/.../tables/seed_variance.tex has the same DATA ROWS as
    the committed one (caption + header + every numeric row + rules), and
    print the seed-variance headline. The provenance comment line is exempt
    from this check by design (see _strip_provenance). Returns True/False."""
    if not TABLE5_OUT.exists():
        print(f"[verify] FAIL: {TABLE5_OUT} does not exist (run render() first)",
              file=sys.stderr)
        return False

    current = TABLE5_OUT.read_text()
    rel = TABLE5_OUT.relative_to(REPO_ROOT).as_posix()
    committed = _git_show(rel)
    if committed is None:
        print(f"[verify] WARN: {rel} is not tracked at HEAD; skipping data-row check")
        ok = True
    else:
        ok = _strip_provenance(current) == _strip_provenance(committed)
        print("[verify] TABLE DATA IDENTICAL (provenance comment may differ by design)"
              if ok else "[verify] TABLE DATA CHANGED — investigate")
        if not ok:
            print(f"[verify] diff against HEAD:{rel} (provenance line excluded):",
                  file=sys.stderr)
            for line in difflib.unified_diff(
                    _strip_provenance(committed).splitlines(),
                    _strip_provenance(current).splitlines(),
                    "committed", "regenerated", lineterm=""):
                print(line, file=sys.stderr)

    # Seed-variance headline straight from the input data, independent of
    # table formatting, so this stays informative even if the table changed.
    sweep = json.loads((DATA_SEED_DIV2K / "seed_sweep.json").read_text())
    per = sweep["per_ordering"]
    orderings = [o for o in ("bg", "lr", "rl") if o in per and per[o]["per_seed"]]
    n = per[orderings[0]]["agg"]["0.2"]["n"] if orderings else 0
    print(f"[verify] seed-variance headline: n={n} seeds, orderings={orderings}")
    for o in orderings:
        a = per[o]["agg"].get("0.2")
        if a:
            print(f"[verify]   {o}: PSNR@.20 = {a['mean']:.2f} +/- {a['std']:.2f} dB "
                  f"(min {a['min']:.2f})")
    classical_path = DATA_SEED_REF / "classical_div2k.json"
    if classical_path.exists():
        classical = json.loads(classical_path.read_text())
        bf = classical.get("block_fft_8", {}).get("psnr", {}).get("0.2")
        if bf is not None:
            print(f"[verify]   block-FFT 8x8 reference @ .20 = {bf:.2f} dB")

    return ok


# ===========================================================================
# retrain() — rerun the seed sweep (GPU + dataset submodules required; does
# not run in-sandbox). See the docstring below for exactly what this does
# and does not regenerate.
# ===========================================================================
def _run_module_main(script_path: Path, argv: list[str]) -> int:
    """Load `script_path` as a module (without executing its __main__ guard)
    and call its main() with a patched sys.argv, equivalent to
    `python script_path <argv...>` but in-process. Used to fold the
    qft_seed_sweep driver without re-implementing its training loop and
    without modifying the original file."""
    spec = importlib.util.spec_from_file_location(script_path.stem, script_path)
    mod = importlib.util.module_from_spec(spec)
    old_argv = sys.argv
    try:
        sys.argv = [str(script_path)] + argv
        spec.loader.exec_module(mod)
        return mod.main()
    finally:
        sys.argv = old_argv


def _parse_seed_spec(spec: str) -> list[int]:
    seeds: set[int] = set()
    for part in spec.split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            lo, hi = part.split("-", 1)
            seeds.update(range(int(lo), int(hi) + 1))
        else:
            seeds.add(int(part))
    return sorted(seeds)


def _compute_init_distribution(dataset: str, seeds_spec: str, topk_ratio: float,
                                batch: int, gpu: int | None, out_base: Path) -> Path:
    """Port of render_init_distribution.py's _compute(): Haar-init L0 +
    PCA-parameter-vector spread across seeds. Writes ONLY
    <out_base>/reference/init_distribution.json (no plotting here — Fig 9a
    is drawn separately by render_fig11a_init_distribution() from this JSON,
    which keeps this compute step from writing figures into data/)."""
    if gpu is not None:
        os.environ["CUDA_VISIBLE_DEVICES"] = str(gpu)
        os.environ.setdefault("CUDA_DEVICE_ORDER", "PCI_BUS_ID")
    os.environ.setdefault("XLA_PYTHON_CLIENT_PREALLOCATE", "false")

    import jax.numpy as jnp
    import pdft
    from pdft_benchmarks import datasets as ds_mod
    from pdft_benchmarks.bases import family_random_basis
    from pdft_benchmarks.unfreeze import _make_gradnorm_probe

    dataset_cfg = {"quickdraw_5q": (5, "load_quickdraw", "img_size"),
                   "div2k_8q": (8, "load_div2k", "size"),
                   "tuberlin_8q": (8, "load_tuberlin", "size")}
    m_q, loader_name, size_kw = dataset_cfg[dataset]
    m = n = m_q
    seeds = _parse_seed_spec(seeds_spec)

    train_pool, _ = getattr(ds_mod, loader_name)(
        n_train=500, n_test=50, seed=42, **{size_kw: 2 ** m})
    batch_imgs = jnp.stack([jnp.asarray(x, dtype=jnp.complex128)
                            for x in train_pool[:batch]], axis=0)
    k_train = max(1, round(2 ** (m + n) * topk_ratio))
    loss = pdft.MSELoss(k=k_train)

    print(f"[retrain][init-dist] {dataset} m=n={m} k_train={k_train} "
          f"batch={batch} seeds={len(seeds)}")
    probe = _make_gradnorm_probe(family_random_basis("qft", m, n, 0), loss)
    L0, G0, vecs = [], [], []
    for s in seeds:
        b = family_random_basis("qft", m, n, s)
        loss0, g0 = probe([jnp.asarray(t) for t in b.tensors], batch_imgs, None)
        L0.append(loss0)
        G0.append(g0)
        vecs.append(np.concatenate([
            np.concatenate([np.asarray(t).real.ravel(), np.asarray(t).imag.ravel()])
            for t in b.tensors]))

    L0 = np.asarray(L0)
    X = np.asarray(vecs)
    Xc = X - X.mean(0, keepdims=True)
    U, S, Vt = np.linalg.svd(Xc, full_matrices=False)
    scores = Xc @ Vt[:2].T
    var_ratio = (S[:2] ** 2) / (S ** 2).sum()

    ref_dir = out_base / "reference"
    ref_dir.mkdir(parents=True, exist_ok=True)
    out = ref_dir / "init_distribution.json"
    out.write_text(json.dumps({
        "dataset": dataset, "topk_ratio": topk_ratio,
        "batch": batch, "seeds": seeds,
        "L0": {str(s): float(v) for s, v in zip(seeds, L0)},
        "grad_norm0": {str(s): float(v) for s, v in zip(seeds, G0)},
        "L0_stats": {"mean": float(L0.mean()), "std": float(L0.std(ddof=1)),
                     "min": float(L0.min()), "max": float(L0.max())},
        "pca": {"explained_var_ratio": [float(v) for v in var_ratio],
                "coords": {str(s): [float(scores[i, 0]), float(scores[i, 1])]
                           for i, s in enumerate(seeds)}},
    }, indent=2))
    print(f"[retrain][init-dist] wrote {out}")
    return out


def retrain(gpu: int | None = None) -> int:
    """Rerun the seed sweep, regenerating appendix-C inputs INTO
    data/direct_training/... Needs a GPU + the DIV2K/QuickDraw dataset
    submodules; does not execute in this sandbox.

    Coverage (please read before assuming this regenerates everything):

    - experiments/_train/qft_seed_sweep.py IS the generator of
      data/direct_training/random_seed/div2k_8q/seed_sweep.json (+
      trained_seed_*.json) — Table 5's direct input. Folded in below,
      redirected via --out into DATA_SEED_DIV2K.

    - render_init_distribution.py's own --gpu compute path (NOT
      qft_seed_sweep) produces
      data/direct_training/random_seed/div2k_8q/reference/init_distribution.json
      (Fig 9a's input). Its core is ported inline as
      _compute_init_distribution() above (writing only the JSON, not
      figures, so it doesn't pollute data/ with rendered PDFs) rather than
      calling that renderer's main() wholesale.

    - Fig 9b's unfreeze trace.json files
      (data/direct_training/unfreeze/<dataset>/<init>/<ordering>/trace.json)
      have NO in-repo regenerator. Their actual generator was
      experiments/qft/qft_direct_training.py's `unfreeze` subcommand, which
      was deleted in commit 7a90d53 ("chore(experiments): drop drivers with
      no figure in the paper") — despite the data it produced feeding Fig 9b.
      Recovering it (`git show 7a90d53^:experiments/qft/qft_direct_training.py`)
      is a prerequisite for a from-scratch Fig 9b regen; not reimplemented
      here.

    - Fig 9c's seed_scatter_ratios.json has NO in-repo generator either. Its
      own docstring says it is merged from reference/_multiratio_<ordering>.json
      partials, but neither those partials nor a merge script exist anywhere
      in this repo's git history (searched, incl. deleted files). Not wired.
    """
    print(
        "[retrain] NOTE: two of the four committed appendix-C inputs are "
        "NOT regenerated by --retrain — their original from-scratch "
        "generators are not present on main:\n"
        "[retrain]   - Fig 9b  data/direct_training/unfreeze/**/trace.json "
        "(generator experiments/qft/qft_direct_training.py `unfreeze` was "
        "removed in commit 7a90d53)\n"
        "[retrain]   - Fig 9c data/direct_training/random_seed/div2k_8q/"
        "reference/seed_scatter_ratios.json (no merge script for its "
        "_multiratio_<ordering>.json partials exists in this repo's "
        "history)\n"
        "[retrain] Both remain as committed inputs that render()/verify() "
        "read and check; only the two sweeps below are actually rerun.",
        file=sys.stderr)

    print("[retrain] === qft_seed_sweep: random-seed sweep "
          "(Table 5 + trained-operator input for Fig 9a/b) ===")
    argv_common = ["--gpu", str(gpu)] if gpu is not None else []
    rc = _run_module_main(
        REPO_ROOT / "experiments/_train/qft_seed_sweep.py",
        argv_common + ["--dataset", "div2k_8q", "--orderings", "bg,lr,rl",
                       "--seeds", "1-100", "--out", str(DATA_SEED_DIV2K)])
    if rc != 0:
        print(f"[retrain] qft_seed_sweep exited {rc}", file=sys.stderr)
        return rc

    print("[retrain] === init-distribution compute: Fig 9a input ===")
    _compute_init_distribution(
        dataset="div2k_8q", seeds_spec="1-100", topk_ratio=0.20, batch=50,
        gpu=gpu, out_base=DATA_SEED_DIV2K)

    print(
        "[retrain] done. Reminder: Fig 9b trace.json and Fig 9c "
        "seed_scatter_ratios.json were left untouched (no in-repo generator "
        "— see the NOTE above / retrain() docstring).",
        file=sys.stderr)
    return 0


# ===========================================================================
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--retrain", action="store_true", default=False,
                    help="Rerun the seed sweep to regenerate data/ "
                         "inputs (needs GPU + dataset submodules; see "
                         "retrain()'s docstring for what is and isn't "
                         "covered). Default: render + verify only.")
    ap.add_argument("--gpu", type=int, default=None,
                    help="GPU index, forwarded to --retrain sub-drivers.")
    args = ap.parse_args(argv)

    if args.retrain:
        return retrain(gpu=args.gpu)

    render()
    ok = verify()
    return 0 if ok else 1


if __name__ == "__main__":
    sys.exit(main())
