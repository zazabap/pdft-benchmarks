# Table 5 — seed-variance LaTeX table.
# Ports tools/analysis/render_seed_variance_table.py main().
# ===========================================================================
_RHOS = ["0.05", "0.1", "0.15", "0.2"]
_TABLE_LABEL = {"bg": "block-growth", "lr": r"left$\to$right", "rl": r"right$\to$left"}


def _build_seed_variance_table(seed_sweep_path: Path, classical_path: Path):
    """Returns (text, meta); meta = {"n": int, "orderings": [...]}.

    NOTE on the first table line: the provenance comment names THIS script
    (experiments/04_robustness_qft.py), not the old standalone renderer it
    replaces. The previously-committed results/.../seed_variance.tex carried
    "% Auto-generated by tools/render_seed_variance_table.py" (itself already
    stale — that predates commit 1a70ab5, which moved the tool into
    tools/analysis/ without the .tex ever being re-rendered). Since this
    script is now the actual generator, the comment should say so; only the
    DATA rows are required to stay identical across regenerations, and that's
    what verify() checks (it deliberately ignores this one comment line).
    """
    sweep = json.loads(seed_sweep_path.read_text())
    per = sweep["per_ordering"]
    orderings = [o for o in ("bg", "lr", "rl") if o in per and per[o]["per_seed"]]
    if not orderings:
        raise RuntimeError("[table5] no populated orderings")
    classical = None
    if classical_path.exists():
        classical = json.loads(classical_path.read_text())

    best = {r: max(per[o]["agg"][r]["mean"] for o in orderings if r in per[o]["agg"])
            for r in _RHOS}

    def fmt_cell(o, r):
        a = per[o]["agg"].get(r)
        if not a:
            return "--"
        s = f"{a['mean']:.2f}\\,$\\pm$\\,{a['std']:.2f}"
        if abs(a["mean"] - best[r]) < 1e-9:
            s = f"\\textbf{{{s}}}"
        return s

    n = per[orderings[0]]["agg"]["0.2"]["n"]
    lines = [
        r"% Auto-generated by experiments/04_robustness_qft.py — do not edit.",
        r"\begin{tabular}{l" + "r" * len(_RHOS) + r"r}",
        r"\toprule",
        r"configuration & $\rho{=}.05$ & $\rho{=}.10$ & $\rho{=}.15$ & "
        r"$\rho{=}.20$ & min@$.20$ \\",
        r"\midrule",
    ]
    for o in orderings:
        cells = " & ".join(fmt_cell(o, r) for r in _RHOS)
        mn = per[o]["agg"]["0.2"]["min"]
        lines.append(f"{_TABLE_LABEL.get(o, o)} & {cells} & {mn:.2f} \\\\")
    if classical:
        lines.append(r"\midrule")
        for key, lab in (("block_fft_8", "block-FFT 8×8"),
                         ("block_dct_8", "block-DCT 8×8")):
            ps = classical[key]["psnr"]
            cells = " & ".join(f"{ps[r]:.2f}" for r in _RHOS)
            lines.append(f"{lab} & {cells} & -- \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    caption = (f"% n={n} random-init seeds per ordering; top-20\\% training "
               f"objective; mean$\\pm\\sigma$ test PSNR (dB) on the fixed "
               f"DIV2K test set.\n")
    text = caption + "\n".join(lines) + "\n"
    return text, {"n": n, "orderings": orderings}


def render_table5_seed_variance(seed_sweep_path: Path = DATA_SEED_DIV2K / "seed_sweep.json",
                                 classical_path: Path = DATA_SEED_REF / "classical_div2k.json",
                                 write_base: Path = RESULTS_SEED_DIV2K):
    text, meta = _build_seed_variance_table(seed_sweep_path, classical_path)
    out = write_base / "tables" / "seed_variance.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text)
    print(f"[table] wrote {out} (n={meta['n']}, orderings={meta['orderings']})")
    return out, meta


